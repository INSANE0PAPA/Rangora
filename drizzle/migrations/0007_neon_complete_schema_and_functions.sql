-- Trigger: Registration Capacity Guard
CREATE OR REPLACE FUNCTION public.registration_capacity_guard()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  seats integer;
  booked integer;
BEGIN
  IF NEW.kind = 'booked' THEN
    SELECT max_seats INTO seats FROM public.events WHERE id = NEW.event_id AND published;
    IF seats IS NULL THEN
      RAISE EXCEPTION 'Event is not open for registration';
    END IF;

    SELECT count(*) INTO booked FROM public.registrations WHERE event_id = NEW.event_id AND kind = 'booked';
    IF booked >= seats THEN
      RAISE EXCEPTION 'This event has no seats remaining';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS registrations_capacity_trigger ON public.registrations;
CREATE TRIGGER registrations_capacity_trigger
BEFORE INSERT ON public.registrations
FOR EACH ROW EXECUTE FUNCTION public.registration_capacity_guard();

-- Trigger: Synchronize Organiser Application Review to User Roles
CREATE OR REPLACE FUNCTION public.sync_organiser_role_after_review()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.status = 'approved' THEN
    INSERT INTO public.user_roles(user_id, role)
    VALUES (NEW.user_id, 'organizer')
    ON CONFLICT (user_id, role) DO NOTHING;
  ELSIF OLD.status = 'approved' AND NEW.status <> 'approved' THEN
    DELETE FROM public.user_roles WHERE user_id = NEW.user_id AND role = 'organizer';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS organiser_review_sync_trigger ON public.organiser_profiles;
CREATE TRIGGER organiser_review_sync_trigger
AFTER UPDATE OF status ON public.organiser_profiles
FOR EACH ROW EXECUTE FUNCTION public.sync_organiser_role_after_review();

