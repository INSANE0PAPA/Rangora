-- Trigger: Venue and Organiser Schedule Clash Guard
CREATE OR REPLACE FUNCTION public.events_no_clash()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  other text;
BEGIN
  IF NEW.end_at <= NEW.start_at THEN
    RAISE EXCEPTION 'CLASH: Event must end after it starts';
  END IF;

  IF NEW.organiser_id IS NOT NULL THEN
    SELECT name INTO other
    FROM public.events
    WHERE organiser_id = NEW.organiser_id
      AND id <> NEW.id
      AND tstzrange(start_at, end_at) && tstzrange(NEW.start_at, NEW.end_at)
    LIMIT 1;

    IF other IS NOT NULL THEN
      RAISE EXCEPTION 'CLASH: Overlaps your existing event "%"', other;
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS events_no_clash_trigger ON public.events;
CREATE TRIGGER events_no_clash_trigger
BEFORE INSERT OR UPDATE OF start_at, end_at, organiser_id ON public.events
FOR EACH ROW EXECUTE FUNCTION public.events_no_clash();

